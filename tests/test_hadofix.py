"""hadofix's suite: golden Dockerfiles in, expected diffs out, one case per rule.

Each directory under `tests/golden/` holds a Dockerfile, the hadolint JSON for
it (generated by the real linter — see that directory's README) and the two
halves of hadofix's output: the diff on stdout, the report on stderr.
Regenerate them with `make golden` after a deliberate change.
"""

import io
import os
import shutil
from pathlib import Path

import pytest

from hadofix import (
    APT,
    EX_FINDINGS,
    EX_NOINPUT,
    EX_OK,
    EX_UNAVAILABLE,
    Doc,
    Finding,
    fix_apt_lists,
    fix_base_pin,
    fix_pin_packages,
    main,
    own_findings,
    parse_findings,
    parse_ref,
    resolve_digest,
)

GOLDEN = Path(__file__).parent / "golden"
CASES = sorted(path for path in GOLDEN.iterdir() if path.is_dir())
UPDATE_GOLDEN = os.environ.get("HADOFIX_UPDATE_GOLDEN") == "1"


def run_case(
    case: Path,
    tmp_path: Path,
    capsys: pytest.CaptureFixture[str],
    *argv: str,
) -> tuple[int, str, str]:
    """Run hadofix over a copy of `case`, with the temp path scrubbed back out."""
    shutil.copytree(case, tmp_path, dirs_exist_ok=True)
    code = main([str(tmp_path / "Dockerfile"), "--from-json", str(tmp_path / "hadolint.json"), *argv])
    captured = capsys.readouterr()
    return (
        code,
        captured.out.replace(f"{tmp_path}{os.sep}", ""),
        captured.err.replace(f"{tmp_path}{os.sep}", ""),
    )


@pytest.mark.parametrize("case", CASES, ids=lambda case: case.name)
def test_golden(case: Path, tmp_path: Path, capsys: pytest.CaptureFixture[str]) -> None:
    code, diff, report = run_case(case, tmp_path, capsys)
    if UPDATE_GOLDEN:
        (case / "expected.diff").write_text(diff)
        (case / "expected.report").write_text(report)
    assert diff == (case / "expected.diff").read_text()
    assert report == (case / "expected.report").read_text()
    # Without --write nothing on disk changed, so a printed diff is still a
    # finding as far as a CI gate is concerned.
    unresolved = bool(diff) or "left for you" in report
    assert code == (EX_FINDINGS if unresolved else EX_OK)


@pytest.mark.parametrize("case", CASES, ids=lambda case: case.name)
def test_our_own_rules_are_idempotent(case: Path, tmp_path: Path, capsys: pytest.CaptureFixture[str]) -> None:
    """Fixing a file twice changes it once.

    The second run is driven by an empty hadolint payload, which is what the
    linter answers for whatever hadofix already fixed; the HF rules recompute
    themselves from the rewritten file and have to stay quiet.
    """
    run_case(case, tmp_path, capsys, "--write")
    (tmp_path / "hadolint.json").write_text("[]")
    fixed = (tmp_path / "Dockerfile").read_text()
    main([str(tmp_path / "Dockerfile"), "--from-json", str(tmp_path / "hadolint.json"), "--write"])
    again, _report = capsys.readouterr()
    assert again == "", "the second run has nothing left to change"
    assert (tmp_path / "Dockerfile").read_text() == fixed


def test_write_applies_the_diff(tmp_path: Path, capsys: pytest.CaptureFixture[str]) -> None:
    case = GOLDEN / "dl3015-no-install-recommends"
    _code, diff, _report = run_case(case, tmp_path, capsys, "--write")
    assert "--no-install-recommends" in (tmp_path / "Dockerfile").read_text()
    assert diff, "the diff is still printed when it is applied"


def test_nothing_is_written_without_write(tmp_path: Path, capsys: pytest.CaptureFixture[str]) -> None:
    case = GOLDEN / "dl3015-no-install-recommends"
    run_case(case, tmp_path, capsys)
    assert (tmp_path / "Dockerfile").read_text() == (case / "Dockerfile").read_text()


def test_reads_hadolint_json_from_stdin(
    tmp_path: Path,
    capsys: pytest.CaptureFixture[str],
    monkeypatch: pytest.MonkeyPatch,
) -> None:
    dockerfile = tmp_path / "Dockerfile"
    dockerfile.write_text('FROM alpine:3.22\nUSER 10001\nCMD ["/app"]\n')
    payload = '[{"file":"Dockerfile","line":1,"column":1,"level":"info","code":"DL3059","message":"Multiple RUNs"}]'
    monkeypatch.setattr("sys.stdin", io.StringIO(payload))
    assert main([str(dockerfile), "--from-json", "-"]) == EX_FINDINGS
    assert "DL3059" in capsys.readouterr().err


def test_unknown_rules_are_listed_not_guessed_at(tmp_path: Path, capsys: pytest.CaptureFixture[str]) -> None:
    dockerfile = tmp_path / "Dockerfile"
    dockerfile.write_text('FROM alpine:3.22\nUSER 10001\nCMD ["/app"]\n')
    payload = tmp_path / "hadolint.json"
    payload.write_text('[{"line":1,"level":"error","code":"DL3011","message":"Valid UNIX ports"}]')
    assert main([str(dockerfile), "--from-json", str(payload)]) == EX_FINDINGS
    out, err = capsys.readouterr()
    assert out == "", "a rule hadofix cannot fix produces no diff"
    assert "DL3011" in err


