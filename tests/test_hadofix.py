@pytest.mark.parametrize(
    ("ref", "expected"),
    [
        ("ubuntu", ("ubuntu", None, None)),
        ("ubuntu:24.04", ("ubuntu", "24.04", None)),
        ("registry.example.com:5000/app", ("registry.example.com:5000/app", None, None)),
        ("registry.example.com:5000/app:1.2", ("registry.example.com:5000/app", "1.2", None)),
        (f"alpine:3.22@sha256:{'a' * 64}", ("alpine", "3.22", f"sha256:{'a' * 64}")),
    ],
)
def test_parse_ref(ref: str, expected: tuple[str, str | None, str | None]) -> None:
    assert parse_ref(ref) == expected


def test_a_comment_inside_a_continuation_does_not_end_the_instruction() -> None:
    doc = Doc("FROM alpine:3.22\nRUN echo one \\\n# why we do this\n && echo two\n", Path("Dockerfile"))
    run = next(inst for inst in doc.instructions() if inst.keyword == "RUN")
    assert run.text == "RUN echo one && echo two"
    assert (run.start, run.end) == (1, 3)


def test_apt_cleanup_joins_a_multi_line_run() -> None:
    doc = Doc(
        "FROM debian:bookworm-slim\nRUN apt-get update \\\n && apt-get install -y curl\n",
        Path("Dockerfile"),
    )
    assert fix_apt_lists(doc, Finding("DL3009", 2, "info", "")).__class__.__name__ == "Fixed"
    assert doc.text.endswith(" && apt-get install -y curl \\\n && rm -rf /var/lib/apt/lists/*\n")


def test_pipefail_picks_the_shell_the_base_image_has(tmp_path: Path, capsys: pytest.CaptureFixture[str]) -> None:
    dockerfile = tmp_path / "Dockerfile"
    dockerfile.write_text('FROM alpine:3.22\nRUN wget -qO- http://x | tar -xz\nUSER 10001\nCMD ["/app"]\n')
    payload = tmp_path / "hadolint.json"
    payload.write_text('[{"line":2,"level":"warning","code":"DL4006","message":"Set the SHELL option -o pipefail"}]')
    main([str(dockerfile), "--from-json", str(payload), "--write"])
    capsys.readouterr()
    assert '/bin/ash", "-o", "pipefail"' in dockerfile.read_text()


def test_a_version_is_taken_from_evidence_never_invented() -> None:
    doc = Doc("FROM debian:bookworm-slim\nRUN apt-get install -y curl\n", Path("Dockerfile"))
    refusal = fix_pin_packages(APT, doc, Finding("DL3008", 2, "warning", ""))
    assert "`curl`" in refusal.why
    assert doc.text.count("curl") == 1, "a refused fix leaves the file alone"


def test_a_stage_is_never_evidence_for_itself() -> None:
    """`FROM python:latest` is the finding, so it cannot also be the answer."""
    doc = Doc("FROM python:latest\n", Path("Dockerfile"))
    refusal = fix_base_pin(doc, Finding("DL3007", 1, "warning", ""))
    assert "--resolve-digests" in refusal.why
    assert doc.text == "FROM python:latest\n"


def test_the_base_pin_uses_the_resolver_only_when_the_file_has_no_answer() -> None:
    doc = Doc("FROM ubuntu\n", Path("Dockerfile"), resolver=lambda image, tag: f"sha256:{'0' * 64}")
    assert fix_base_pin(doc, Finding("DL3006", 1, "warning", "")).__class__.__name__ == "Fixed"
    assert doc.text == f"FROM ubuntu@sha256:{'0' * 64}\n"

    without = Doc("FROM ubuntu\n", Path("Dockerfile"))
    assert "--resolve-digests" in fix_base_pin(without, Finding("DL3006", 1, "warning", "")).why
    assert without.text == "FROM ubuntu\n"


def test_an_init_in_the_entrypoint_answers_hf1003() -> None:
    forking = Doc('FROM nginx:1.27\nUSER 10001\nCMD ["nginx", "-g", "daemon off;"]\n', Path("Dockerfile"))
    assert [f.code for f in own_findings(forking)] == ["HF1003"]

    with_init = Doc(
        'FROM nginx:1.27\nUSER 10001\nENTRYPOINT ["/sbin/tini", "--"]\nCMD ["nginx", "-g", "daemon off;"]\n',
        Path("Dockerfile"),
    )
    assert [f.code for f in own_findings(with_init)] == []


def test_an_entrypoint_script_that_execs_answers_hf1002(tmp_path: Path) -> None:
    (tmp_path / "entrypoint.sh").write_text('#!/bin/sh\nset -e\nexec "$@"\n')
    doc = Doc(
        'FROM alpine:3.22\nCOPY entrypoint.sh /entrypoint.sh\nUSER 10001\nENTRYPOINT ["/entrypoint.sh"]\n',
        tmp_path / "Dockerfile",
    )
    assert [f.code for f in own_findings(doc)] == []


def test_a_script_copied_with_the_build_context_is_still_found(tmp_path: Path) -> None:
    (tmp_path / "entrypoint.sh").write_text('#!/bin/sh\n/usr/local/bin/app "$@"\n')
    doc = Doc(
        'FROM alpine:3.22\nCOPY . /app\nUSER 10001\nENTRYPOINT ["/app/entrypoint.sh"]\n',
        tmp_path / "Dockerfile",
    )
    assert [f.code for f in own_findings(doc)] == ["HF1002"]


