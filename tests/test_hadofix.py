@pytest.mark.skipif(shutil.which("hadolint") is None, reason="hadolint is not installed")
def test_hadolint_drives_one_pass_to_clean(tmp_path: Path, capsys: pytest.CaptureFixture[str]) -> None:
    """One --write pass, and the linter that asked for the changes is quiet."""
    dockerfile = tmp_path / "Dockerfile"
    dockerfile.write_text(
        "FROM debian:bookworm-slim\n"
        "RUN apt-get update && apt-get install -y curl=7.88.1-10+deb12u5\n"
        "CMD /usr/local/bin/app --port 8080\n"
    )
    assert main([str(dockerfile), "--write"]) == EX_OK
    capsys.readouterr()
    assert main([str(dockerfile)]) == EX_OK
    assert capsys.readouterr().out == "", "a second pass has nothing to say"
